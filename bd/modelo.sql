-- ---------------------------------------------------------------------
-- 10. TRIGGER: conservar_hasta de documento
-- ---------------------------------------------------------------------

CREATE FUNCTION fn_documento_conservar_hasta() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_anios smallint;
BEGIN
    IF NEW.conservar_hasta IS NOT NULL
       AND (TG_OP = 'INSERT' OR NEW.conservar_hasta IS DISTINCT FROM OLD.conservar_hasta) THEN
        RETURN NEW;   -- fecha indicada a mano: se respeta
    END IF;

    SELECT anios_conservacion INTO STRICT v_anios
      FROM tipo_documento
     WHERE id_tipo_documento = NEW.id_tipo_documento;

    NEW.conservar_hasta := (NEW.fecha_documento + make_interval(years => v_anios))::date;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_documento_conservar_hasta
    BEFORE INSERT OR UPDATE OF id_tipo_documento, fecha_documento, conservar_hasta
    ON documento
    FOR EACH ROW EXECUTE FUNCTION fn_documento_conservar_hasta();

-- ---------------------------------------------------------------------
-- 11. TRIGGER: auditoría de cambios en cuenta_bancaria (decisión D21)
-- ---------------------------------------------------------------------

CREATE FUNCTION fn_enmascarar_iban(p_iban text) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE WHEN p_iban IS NULL THEN NULL
                ELSE repeat('*', greatest(length(p_iban) - 4, 0)) || right(p_iban, 4)
           END
$$;

CREATE FUNCTION fn_auditar_cuenta_bancaria() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_campo  text;
    v_old    text;
    v_new    text;
    v_jold   jsonb;
    v_jnew   jsonb;
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO auditoria_cambio (tabla, id_registro, campo, operacion, valor_anterior, valor_nuevo)
        VALUES (TG_TABLE_NAME, NEW.id_cuenta, 'iban', 'I', NULL, fn_enmascarar_iban(NEW.iban));
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        INSERT INTO auditoria_cambio (tabla, id_registro, campo, operacion, valor_anterior, valor_nuevo)
        VALUES (TG_TABLE_NAME, OLD.id_cuenta, 'iban', 'D', fn_enmascarar_iban(OLD.iban), NULL);
        RETURN OLD;
    END IF;

    -- UPDATE: una fila de auditoría por cada campo que cambia
    v_jold := to_jsonb(OLD);
    v_jnew := to_jsonb(NEW);
    FOR v_campo IN SELECT jsonb_object_keys(v_jnew) LOOP
        CONTINUE WHEN v_campo = 'id_cuenta';
        v_old := v_jold ->> v_campo;
        v_new := v_jnew ->> v_campo;
        IF v_old IS DISTINCT FROM v_new THEN
            IF v_campo = 'iban' THEN
                v_old := fn_enmascarar_iban(v_old);
                v_new := fn_enmascarar_iban(v_new);
            END IF;
            INSERT INTO auditoria_cambio (tabla, id_registro, campo, operacion, valor_anterior, valor_nuevo)
            VALUES (TG_TABLE_NAME, NEW.id_cuenta, v_campo, 'U', v_old, v_new);
        END IF;
    END LOOP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_auditar_cuenta_bancaria
    AFTER INSERT OR UPDATE OR DELETE
    ON cuenta_bancaria
    FOR EACH ROW EXECUTE FUNCTION fn_auditar_cuenta_bancaria();

COMMIT;
