BEGIN;

-- ---------------------------------------------------------------------
-- 1. ORGANIZACIÓN
-- ---------------------------------------------------------------------

CREATE TABLE departamento (
    id_departamento  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           varchar(40) NOT NULL,
    CONSTRAINT uq_departamento_nombre UNIQUE (nombre)
);

CREATE TABLE empleado (
    id_empleado      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_departamento  smallint NOT NULL REFERENCES departamento (id_departamento) ON DELETE RESTRICT,
    sede             varchar(10) NOT NULL,
    usuario_ad       varchar(20) NOT NULL,         -- cuenta del dominio
    nombre           varchar(60) NOT NULL,
    apellidos        varchar(100) NOT NULL,
    email            varchar(120) NOT NULL,
    activo           boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_empleado_usuario_ad UNIQUE (usuario_ad),
    CONSTRAINT uq_empleado_email UNIQUE (email),
    CONSTRAINT ck_empleado_sede CHECK (sede IN ('ZARAGOZA', 'HUESCA', 'TERUEL'))
);

-- ---------------------------------------------------------------------
-- 2. CLIENTES Y SERVICIOS
-- ---------------------------------------------------------------------

CREATE TABLE cliente (
    id_cliente       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_cliente     char(1) NOT NULL,             -- E empresa, A autónomo
    nif              varchar(9) NOT NULL,          -- NIF o CIF
    denominacion     varchar(150) NOT NULL,        -- razón social o nombre completo
    direccion        varchar(150),
    codigo_postal    char(5),
    localidad        varchar(80),
    telefono         varchar(15),
    email            varchar(120),
    fecha_alta       date NOT NULL DEFAULT current_date,
    fecha_baja       date,                         -- NULL si sigue activo
    CONSTRAINT uq_cliente_nif UNIQUE (nif),
    CONSTRAINT ck_cliente_tipo CHECK (tipo_cliente IN ('E', 'A')),
    CONSTRAINT ck_cliente_fechas CHECK (fecha_baja IS NULL OR fecha_baja >= fecha_alta)
);

CREATE TABLE contacto_cliente (
    id_contacto      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente       integer NOT NULL REFERENCES cliente (id_cliente) ON DELETE CASCADE,
    nombre           varchar(100) NOT NULL,
    cargo            varchar(60),
    telefono         varchar(15),
    email            varchar(120)
);

CREATE TABLE servicio (
    id_servicio      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           varchar(10) NOT NULL,
    nombre           varchar(60) NOT NULL,
    id_departamento  smallint NOT NULL REFERENCES departamento (id_departamento) ON DELETE RESTRICT,
    CONSTRAINT uq_servicio_codigo UNIQUE (codigo)
);

-- Tabla intermedia de la relación N:M cliente - servicio
CREATE TABLE contratacion (
    id_contratacion          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente               integer NOT NULL REFERENCES cliente (id_cliente) ON DELETE RESTRICT,
    id_servicio              smallint NOT NULL REFERENCES servicio (id_servicio) ON DELETE RESTRICT,
    id_empleado_responsable  integer NOT NULL REFERENCES empleado (id_empleado) ON DELETE RESTRICT,
    fecha_alta               date NOT NULL DEFAULT current_date,
    fecha_baja               date,
    cuota_mensual            numeric(10,2) NOT NULL,
    CONSTRAINT uq_contratacion UNIQUE (id_cliente, id_servicio, fecha_alta),
    CONSTRAINT ck_contratacion_cuota CHECK (cuota_mensual >= 0)
);

-- ---------------------------------------------------------------------
-- 3. TRABAJADORES DE LOS CLIENTES
-- ---------------------------------------------------------------------

CREATE TABLE trabajador (
    id_trabajador        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente           integer NOT NULL REFERENCES cliente (id_cliente) ON DELETE RESTRICT,
    documento_identidad  varchar(9) NOT NULL,      -- DNI o NIE
    num_afiliacion       varchar(12),              -- Seguridad Social
    nombre               varchar(60) NOT NULL,
    apellidos            varchar(100) NOT NULL,
    puesto               varchar(80),
    tipo_contrato        varchar(15) NOT NULL,
    fecha_alta           date NOT NULL,
    fecha_baja           date,
    CONSTRAINT uq_trabajador_cliente_documento UNIQUE (id_cliente, documento_identidad),
    CONSTRAINT uq_trabajador_id_cliente UNIQUE (id_trabajador, id_cliente),
    CONSTRAINT ck_trabajador_tipo_contrato CHECK (tipo_contrato IN ('INDEFINIDO', 'TEMPORAL', 'FORMACION', 'OTRO'))
);

-- Cuentas de clientes o de trabajadores (cambios auditados por trigger)
CREATE TABLE cuenta_bancaria (
    id_cuenta        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente       integer REFERENCES cliente (id_cliente) ON DELETE RESTRICT,
    id_trabajador    integer REFERENCES trabajador (id_trabajador) ON DELETE RESTRICT,
    titular          varchar(120) NOT NULL,
    iban             varchar(34) NOT NULL,         -- solo lo ve el rol autorizado
    vigente          boolean NOT NULL DEFAULT true,
    fecha_alta       date NOT NULL DEFAULT current_date,
    fecha_baja       date,
    CONSTRAINT ck_cuenta_titular_exclusivo CHECK (num_nonnulls(id_cliente, id_trabajador) = 1)
);

CREATE UNIQUE INDEX uq_cuenta_vigente_cliente
    ON cuenta_bancaria (id_cliente) WHERE vigente AND id_cliente IS NOT NULL;
CREATE UNIQUE INDEX uq_cuenta_vigente_trabajador
    ON cuenta_bancaria (id_trabajador) WHERE vigente AND id_trabajador IS NOT NULL;

-- ---------------------------------------------------------------------
-- 4. DOCUMENTOS (solo metadatos y ruta; el fichero vive en el servidor de ficheros)
-- ---------------------------------------------------------------------

CREATE TABLE tipo_documento (
    id_tipo_documento   smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              varchar(60) NOT NULL,      -- contrato, factura, nómina, justificante...
    nivel               varchar(20) NOT NULL,
    anios_conservacion  smallint NOT NULL,
    CONSTRAINT uq_tipo_documento_nombre UNIQUE (nombre),
    CONSTRAINT ck_tipo_documento_nivel CHECK (nivel IN ('PUBLICA', 'INTERNA', 'CONFIDENCIAL', 'ESPECIAL')),
    CONSTRAINT ck_tipo_documento_anios CHECK (anios_conservacion > 0)
);

CREATE TABLE documento (
    id_documento        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente          integer NOT NULL REFERENCES cliente (id_cliente) ON DELETE RESTRICT,
    id_trabajador       integer,                   -- opcional
    id_tipo_documento   smallint NOT NULL REFERENCES tipo_documento (id_tipo_documento) ON DELETE RESTRICT,
    fecha_documento     date NOT NULL,
    ruta_fichero        varchar(260) NOT NULL,     -- ruta en el servidor de ficheros
    hash_sha256         char(64) NOT NULL,         -- integridad
    conservar_hasta     date,                      -- lo calcula un trigger; ampliable por bloqueo legal
    id_empleado_alta    integer NOT NULL REFERENCES empleado (id_empleado) ON DELETE RESTRICT,
    CONSTRAINT uq_documento_ruta UNIQUE (ruta_fichero),
    CONSTRAINT fk_documento_trabajador_cliente FOREIGN KEY (id_trabajador, id_cliente)
        REFERENCES trabajador (id_trabajador, id_cliente) ON DELETE RESTRICT,
    CONSTRAINT ck_documento_conservacion CHECK (conservar_hasta IS NULL OR conservar_hasta >= fecha_documento)
);

-- ---------------------------------------------------------------------
-- 5. NÓMINAS (14 pagas al año)
-- ---------------------------------------------------------------------

CREATE TABLE nomina (
    id_nomina        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_trabajador    integer NOT NULL REFERENCES trabajador (id_trabajador) ON DELETE RESTRICT,
    periodo          date NOT NULL,                -- primer día del mes de devengo
    tipo_paga        varchar(15) NOT NULL,
    bruto            numeric(10,2) NOT NULL,
    deducciones      numeric(10,2) NOT NULL,       -- total
    liquido          numeric(10,2) GENERATED ALWAYS AS (bruto - deducciones) STORED,
    id_documento     integer REFERENCES documento (id_documento) ON DELETE RESTRICT,   -- PDF, opcional
    CONSTRAINT uq_nomina_trabajador_periodo UNIQUE (id_trabajador, periodo, tipo_paga),
    CONSTRAINT uq_nomina_documento UNIQUE (id_documento),
    CONSTRAINT ck_nomina_tipo_paga CHECK (tipo_paga IN ('ORDINARIA', 'EXTRA_JUNIO', 'EXTRA_DICIEMBRE')),
    CONSTRAINT ck_nomina_importes CHECK (deducciones BETWEEN 0 AND bruto)
);

-- ---------------------------------------------------------------------
-- 6. OBLIGACIONES FISCALES Y LABORALES
-- ---------------------------------------------------------------------

CREATE TABLE tipo_obligacion (
    id_tipo_obligacion  smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              varchar(10) NOT NULL,      -- p. ej. 303, 111, 200
    nombre              varchar(100) NOT NULL,
    ambito              char(1) NOT NULL,          -- F fiscal, L laboral
    periodicidad        char(1) NOT NULL,          -- M mensual, T trimestral, A anual
    CONSTRAINT uq_tipo_obligacion_codigo UNIQUE (codigo),
    CONSTRAINT ck_tipo_obligacion_ambito CHECK (ambito IN ('F', 'L')),
    CONSTRAINT ck_tipo_obligacion_periodicidad CHECK (periodicidad IN ('M', 'T', 'A'))
);

CREATE TABLE obligacion (
    id_obligacion              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente                 integer NOT NULL REFERENCES cliente (id_cliente) ON DELETE RESTRICT,
    id_tipo_obligacion         smallint NOT NULL REFERENCES tipo_obligacion (id_tipo_obligacion) ON DELETE RESTRICT,
    ejercicio                  smallint NOT NULL,  -- año
    periodo                    varchar(4) NOT NULL, -- 01 a 12, 1T a 4T, AN
    fecha_limite               date NOT NULL,
    estado                     varchar(10) NOT NULL DEFAULT 'PENDIENTE',
    fecha_presentacion         date,
    id_empleado_responsable    integer NOT NULL REFERENCES empleado (id_empleado) ON DELETE RESTRICT,
    id_documento_justificante  integer REFERENCES documento (id_documento) ON DELETE RESTRICT,   -- opcional
    CONSTRAINT uq_obligacion UNIQUE (id_cliente, id_tipo_obligacion, ejercicio, periodo),
    CONSTRAINT uq_obligacion_justificante UNIQUE (id_documento_justificante),
    CONSTRAINT ck_obligacion_estado CHECK (estado IN ('PENDIENTE', 'EN_CURSO', 'PRESENTADA', 'ARCHIVADA'))
);

-- ---------------------------------------------------------------------
-- 7. FACTURACIÓN
-- ---------------------------------------------------------------------

CREATE TABLE factura (
    id_factura       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente       integer NOT NULL REFERENCES cliente (id_cliente) ON DELETE RESTRICT,
    numero           varchar(20) NOT NULL,         -- serie y número
    fecha_emision    date NOT NULL,
    periodo_desde    date,
    periodo_hasta    date,
    estado_cobro     varchar(10) NOT NULL DEFAULT 'PENDIENTE',
    fecha_cobro      date,
    CONSTRAINT uq_factura_numero UNIQUE (numero),
    CONSTRAINT ck_factura_periodo CHECK (periodo_hasta >= periodo_desde),
    CONSTRAINT ck_factura_estado CHECK (estado_cobro IN ('PENDIENTE', 'COBRADA', 'IMPAGADA', 'ANULADA'))
);

CREATE TABLE linea_factura (
    id_linea         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura       integer NOT NULL REFERENCES factura (id_factura) ON DELETE CASCADE,
    num_linea        smallint NOT NULL,
    id_servicio      smallint REFERENCES servicio (id_servicio) ON DELETE RESTRICT,   -- opcional
    concepto         varchar(200) NOT NULL,
    cantidad         numeric(8,2) NOT NULL,
    precio_unitario  numeric(10,2) NOT NULL,
    tipo_iva         numeric(4,2) NOT NULL DEFAULT 21.00,
    CONSTRAINT uq_linea_factura UNIQUE (id_factura, num_linea),
    CONSTRAINT ck_linea_factura_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_linea_factura_precio CHECK (precio_unitario >= 0)
);

CREATE VIEW v_factura_total AS
SELECT f.id_factura,
       f.numero,
       f.id_cliente,
       COALESCE(round(sum(l.cantidad * l.precio_unitario), 2), 0)                              AS base_imponible,
       COALESCE(round(sum(l.cantidad * l.precio_unitario * l.tipo_iva / 100), 2), 0)           AS iva,
       COALESCE(round(sum(l.cantidad * l.precio_unitario * (1 + l.tipo_iva / 100)), 2), 0)     AS total
  FROM factura f
  LEFT JOIN linea_factura l ON l.id_factura = f.id_factura
 GROUP BY f.id_factura, f.numero, f.id_cliente;

